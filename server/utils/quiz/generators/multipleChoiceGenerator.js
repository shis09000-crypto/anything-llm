const { generateQuestionsForType } = require("./shared");

async function multipleChoiceGenerator(job) {
  return await generateQuestionsForType({
    job,
    systemPrompt:
      "你是一名严谨的中文知识库测验出题专家，专门根据给定 evidence/sourceRefs 生成有证据支持的多选题。除必要的专业术语、缩写、基因/蛋白名、模型名、英文原文概念外，题目和选项必须使用中文。只返回严格 JSON，不要输出任何额外文字。",
    typeRules: `多选题生成规则：
- 中文优先；只有专业名词、标准缩写、基因名、蛋白名、术语原文等确有必要时才保留英文，例如 DNA polymerase、HP1、Okazaki fragment。
- 每道题默认 4-6 个选项；extreme 难度优先使用 6 个选项，但不要为了凑数制造弱选项。
- 每道题必须至少有 2 个正确答案。
- 正确答案数量必须是 2、3 或 4 个。
- 不能所有选项都正确。
- correctAnswer 必须是正确选项 id 组成的数组，例如 ["A", "C"]。
- 选项 id 必须清晰稳定，建议使用 A、B、C、D、E、F。
- 题干必须明确提示“多选”，例如“以下哪些说法正确？”
- 正确选项必须都能被 evidence 明确支持。
- 错误选项必须合理、有迷惑性，但不能被 evidence 支持为正确。
- 错误选项优先使用相近概念、相似机制、常见误解、条件/方向/因果混淆，或改变关键条件的近似正确说法。
- 多选题应优先考察组合理解，而不是简单事实罗列。
- 不要使用“以上皆是”“以上皆非”“无法判断”“都不正确”这类偷懒选项。
- 不要让正确答案数量固定，但不能等于全部选项数量。
- 题干必须清楚、完整，用户不看原文也能理解题目在问什么。
- 不要输出逐项解释、错因分析、薄弱点分析、复习建议或教学分析。
难度规则：
- easy：基础概念识别与直接事实理解，干扰项较弱。
- medium：需要一定推理与知识点关联，干扰项具有相似性。
- high：强调复杂推理、跨知识点理解、细节辨析与真实场景应用。
- extreme：允许使用资料中未直接出现的陌生案例，考察核心概念迁移能力；选项应具有极强迷惑性，差异可能只有细微细节。
- 输出必须是严格 JSON，字段结构必须符合共享生成器要求。`,
  });
}

module.exports = { multipleChoiceGenerator };
